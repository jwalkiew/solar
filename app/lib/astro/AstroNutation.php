  public static function nutation($jde) {
    $T = AstroBase::J2000Century($jde);
    $D = AstroBase::horner($T, 297.85036, 445267.11148, -0.0019142, 1.0 / 189474) * M_PI / 180;
    $M = AstroBase::horner($T, 357.52772, 35999.050340, -0.0001603, -1.0 / 300000) * M_PI / 180;
    $N = AstroBase::horner($T, 134.96298, 477198.867398, 0.0086972, 1.0 / 56250) * M_PI / 180;
    $F = AstroBase::horner($T, 93.27191, 483202.017538, -0.0036825, 1.0 / 327270) * M_PI / 180;
    $omega = AstroBase::horner($T, 125.04452, -1934.136261, 0.0020708, 1.0 / 450000) * M_PI / 180;
    $dPsi = 0;
    $dEps = 0;
    // sum in reverse order to accumulate smaller terms first
    for ($i = count(self::$table22A) - 1; $i >= 0; $i--) {
      $row = self::$table22A[$i];
      $arg = $row[0] * $D + $row[1] * $M + $row[2] * $N + $row[3] * $F + $row[4] * $omega;
      [$s, $c] = AstroBase::sincos($arg);
      $dPsi += $s * ($row[5] + $row[6] * $T);
      $dEps += $c * ($row[7] + $row[8] * $T);
    }
    $dPsi *= 0.0001 / 3600 * (M_PI / 180);
    $dEps *= 0.0001 / 3600 * (M_PI / 180);
    return [$dPsi, $dEps];
  }

  public static function approxNutation($jde) {
    $T = ($jde - AstroBase::J2000) / 36525;
    $omega = (125.04452 - 1934.136261 * $T) * M_PI / 180;
    $L = (280.4665 + 36000.7698 * $T) * M_PI / 180;
    $N = (218.3165 + 481267.8813 * $T) * M_PI / 180;
    [$sOmega, $cOmega] = AstroBase::sincos($omega);
    [$s2L, $c2L] = AstroBase::sincos(2 * $L);
    [$s2N, $c2N] = AstroBase::sincos(2 * $N);
    [$s2Omega, $c2Omega] = AstroBase::sincos(2 * $omega);
    $dPsi = (-17.2 * $sOmega - 1.32 * $s2L - 0.23 * $s2N + 0.21 * $s2Omega) / 3600 * (M_PI / 180);
    $dEps = (9.2 * $cOmega + 0.57 * $c2L + 0.1 * $c2N - 0.09 * $c2Omega) / 3600 * (M_PI / 180);
    return [$dPsi, $dEps];
  }

  public static function meanObliquity($jde) {
    return AstroBase::horner(
      AstroBase::J2000Century($jde),
      (new AstroAngle(false, 23, 26, 21.448))->rad(),
      -46.815 / 3600 * (M_PI / 180),
      -0.00059 / 3600 * (M_PI / 180),
      0.001813 / 3600 * (M_PI / 180)
    );
  }

