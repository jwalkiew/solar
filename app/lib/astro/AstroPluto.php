  public static function heliocentric($jde) {
    $l = 0;
    $b = 0;
    $r = 0;
    $T = AstroBase::J2000Century($jde);
    $J = 34.35 + 3034.9057 * $T;
    $S = 50.08 + 1222.1138 * $T;
    $P = 238.96 + 144.96 * $T;
    foreach (self::$t37 as $t) {
      [$sAlpha, $cAlpha] = AstroBase::sincos(($t['i'] * $J + $t['j'] * $S + $t['k'] * $P) * M_PI / 180);
      $l += $t['lA'] * $sAlpha + $t['lB'] * $cAlpha;
      $b += $t['bA'] * $sAlpha + $t['bB'] * $cAlpha;
      $r += $t['rA'] * $sAlpha + $t['rB'] * $cAlpha;
    }
    $l = ($l + 238.958116 + 144.96 * $T) * M_PI / 180;
    $b = ($b - 3.908239) * M_PI / 180;
    $r += 40.7241346;
    return ['lon' => $l, 'lat' => $b, 'range' => $r];
  }

  public static function astrometric($jde, $earth) {
    $sEps = AstroBase::SOblJ2000;
    $cEps = AstroBase::COblJ2000;
    $f = function ($jde) use ($sEps, $cEps) {
      ['lon' => $lon, 'lat' => $lat, 'range' => $range] = self::heliocentric($jde);
      [$sl, $cl] = AstroBase::sincos($lon);
      [$sb, $cb] = AstroBase::sincos($lat);
      $x = $range * $cl * $cb;
      $y = $range * ($sl * $cb * $cEps - $sb * $sEps);
      $z = $range * ($sl * $cb * $sEps + $sb * $cEps);
      return ['x' => $x, 'y' => $y, 'z' => $z];
    };
    $c = AstroElliptic::astrometricJ2000($f, $jde, $earth);
    return new AstroBaseCoord($c->ra, $c->dec);
  }
