// Writes the GeoNames populated places from cities.json (CC BY 4.0) as PHP tiles of 10 x 10 degrees,
// consumed by app/lib/Places.php for the nearest-place lookup.
// usage: node gen-places.mjs <outDir>
import { writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const outDir = process.argv[2]
if (!outDir) {
  console.error('usage: node gen-places.mjs <outDir>')
  process.exit(1)
}

const TILE = 10
// GeoNames uses international names for a few Polish places; show the Polish ones
const POLISH_NAMES = { 'PL:Warsaw': 'Warszawa' }

const require = createRequire(import.meta.url)
const cities = require('cities.json/cities.json')
const quote = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"

const tiles = new Map()
let count = 0
for (const c of cities) {
  const lat = Number(c.lat)
  const lon = Number(c.lng)
  if (!Number.isFinite(lat) || !Number.isFinite(lon) || !c.name || !/^[A-Z]{2}$/.test(c.country)) {
    continue
  }
  const key = `${Math.floor((lat + 90) / TILE)}-${Math.floor((Math.min(lon, 179.99999) + 180) / TILE)}`
  if (!tiles.has(key)) {
    tiles.set(key, [])
  }
  const name = POLISH_NAMES[`${c.country}:${c.name}`] || c.name
  tiles.get(key).push(`[${quote(name)}, ${lat}, ${lon}, '${c.country}']`)
  count++
}

const dir = join(outDir, 'places')
mkdirSync(dir, { recursive: true })
for (const [key, rows] of [...tiles.entries()].sort()) {
  writeFileSync(join(dir, `${key}.php`),
    '<?php\n// generated by build/gen-places.mjs from GeoNames via cities.json (CC BY 4.0); do not edit\n' +
    'return [\n' + rows.map((r) => '  ' + r + ',\n').join('') + '];\n')
}
console.log(`places: ${count} places in ${tiles.size} tiles`)
