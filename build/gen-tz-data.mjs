// Extracts the encoded quadtree and zone list from @photostructure/tz-lookup (CC0)
// and writes them as an opcache-friendly PHP file consumed by app/lib/TimeZoneLookup.php.
// usage: node gen-tz-data.mjs <outDir>
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { createRequire } from 'node:module'
import { join } from 'node:path'

const outDir = process.argv[2]
if (!outDir) {
  console.error('usage: node gen-tz-data.mjs <outDir>')
  process.exit(1)
}

const require = createRequire(import.meta.url)
const srcPath = require.resolve('@photostructure/tz-lookup')
const src = readFileSync(srcPath, 'utf8')

const data = src.match(/var X="([\x20-\x7e]*)",T=\[/)
const zones = src.match(/,T=(\["[^\]]*"\]);/)
if (!data || !zones) {
  throw new Error('tz.js layout changed: cannot find data string or zone list')
}

// the PHP port mirrors this exact lookup routine; refuse to build if upstream changed it
const lookup = src.slice(src.indexOf(zones[0]) + zones[0].length)
const expected = 'if(W=+W,!(-90<=(Y=+Y)&&Y<=90&&-180<=W&&W<=180))throw new RangeError("invalid coordinates");' +
  'if(90<=Y)return"Etc/GMT";for(var V=-1,S=48*(180+W)/360.00000000000006,U=24*(90-Y)/180.00000000000003,' +
  'Z=0|S,$=0|U,K=96*$+2*Z,K=56*X.charCodeAt(K)+X.charCodeAt(K+1)-1995;K+T.length<3136;)' +
  'K=56*X.charCodeAt(K=8*(V=V+K+1)+4*($=0|(U=2*(U-$)%2))+2*(Z=0|(S=2*(S-Z)%2))+2304)+X.charCodeAt(K+1)-1995;' +
  'return T[K+T.length-3136]}'
if (!lookup.startsWith(expected)) {
  throw new Error('tz.js lookup routine changed: update app/lib/TimeZoneLookup.php and this check')
}

const zoneList = JSON.parse(zones[1])
const quote = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"

const php = '<?php\n' +
  '// generated by build/gen-tz-data.mjs from @photostructure/tz-lookup (CC0-1.0); do not edit\n' +
  'return [\n' +
  '  \'data\' => ' + quote(data[1]) + ',\n' +
  '  \'zones\' => [' + zoneList.map(quote).join(', ') + '],\n' +
  '];\n'

mkdirSync(outDir, { recursive: true })
writeFileSync(join(outDir, 'tz-lookup.php'), php)
console.log(`tz-lookup.php: ${data[1].length} bytes of data, ${zoneList.length} zones`)
