// Converts astronomia VSOP87B planet series and the deltat table into PHP array files
// consumed by app/lib/astro/AstroData.php.
// usage: node gen-astro-data.mjs <outDir>
import { writeFileSync, mkdirSync } from 'node:fs'
import { join } from 'node:path'

const outDir = process.argv[2]
if (!outDir) {
  console.error('usage: node gen-astro-data.mjs <outDir>')
  process.exit(1)
}

const planets = ['earth', 'mercury', 'venus', 'mars', 'jupiter', 'saturn', 'uranus', 'neptune']

const num = (n) => {
  if (!Number.isFinite(n)) throw new Error('non-finite number in data: ' + n)
  if (Object.is(n, -0)) return '-0.0'
  return String(n)
}

const quote = (s) => "'" + s.replace(/\\/g, '\\\\').replace(/'/g, "\\'") + "'"

const emit = (v, indent) => {
  if (typeof v === 'number') return num(v)
  if (typeof v === 'string') return quote(v)
  if (typeof v === 'boolean') return v ? 'true' : 'false'
  if (v === null || v === undefined) return 'null'
  const pad = '  '.repeat(indent + 1)
  const end = '  '.repeat(indent)
  if (Array.isArray(v)) {
    if (v.every((x) => typeof x !== 'object' || x === null)) {
      return '[' + v.map((x) => emit(x, indent)).join(', ') + ']'
    }
    return '[\n' + v.map((x) => pad + emit(x, indent + 1)).join(',\n') + '\n' + end + ']'
  }
  if (typeof v === 'object') {
    const keys = Object.keys(v)
    return '[\n' + keys.map((k) => {
      const key = /^(0|[1-9][0-9]*)$/.test(k) ? k : quote(k)
      return pad + key + ' => ' + emit(v[k], indent + 1)
    }).join(',\n') + '\n' + end + ']'
  }
  throw new Error('unsupported value type: ' + typeof v)
}

const file = (data) => '<?php\n' +
  '// generated by build/gen-astro-data.mjs from astronomia 4.2.0 data (MIT), do not edit\n' +
  'return ' + emit(data, 0) + ';\n'

try {
  mkdirSync(outDir, { recursive: true })
  for (const p of planets) {
    const mod = await import('astronomia/data/vsop87B' + p)
    writeFileSync(join(outDir, 'vsop87b-' + p + '.php'), file(mod.default))
  }
  const dt = await import('astronomia/data/deltat')
  writeFileSync(join(outDir, 'deltat.php'), file(dt.default))
} catch (err) {
  console.error('gen-astro-data failed: ' + err.message)
  process.exit(1)
}
